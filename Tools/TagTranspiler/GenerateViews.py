"""
GenerateViews.py
Generates the pattern of the perception rays of a View as the C++23 partition Views.Raycast.Type:Pattern from
Data/Views/Rays.xml (the single source of the pattern, D311), and the constants of the sight of an agent as the partition
Views.Raycast.Type:Sight from Data/Views/Sight.xml (D310).

    python Tools/TagTranspiler/GenerateViews.py
    python Tools/TagTranspiler/GenerateViews.py --check    # compare with the repo, write nothing (exit 0 equal, 1 not)

Writes Artemis/3_Domain/Views/Raycast/Type/RaycastPattern.ixx and RaycastSightConstant.ixx. Fails (nothing written) on more rows than
k_ViewRayCount (16), on a value that is not a number, on a range that is not positive, or on a sight constant that is not a k_Pascal name,
is repeated, has no doc or a value that is not positive.
"""
import argparse, os, re, sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from Common import CheckBytes, ReportCheck

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(SCRIPT_DIR, "..", ".."))
SOURCE = os.path.join(REPO, "Data", "Views", "Rays.xml")
SIGHT_SOURCE = os.path.join(REPO, "Data", "Views", "Sight.xml")
OUT = os.path.join(REPO, "Artemis", "3_Domain", "Views", "Raycast", "Type", "RaycastPattern.ixx")
SIGHT_OUT = os.path.join(REPO, "Artemis", "3_Domain", "Views", "Raycast", "Type", "RaycastSightConstant.ixx")
MAX_RAYS = 16
HEADER = "// Generated by Tools/TagTranspiler/GenerateViews.py from Data/Views/Rays.xml. Do not edit."
SIGHT_HEADER = "// Generated by Tools/TagTranspiler/GenerateViews.py from Data/Views/Sight.xml. Do not edit."

def Fail(message: str) -> None:
    sys.exit("ERROR: " + message)

def Number(value: str, what: str) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        Fail(f"{what}: '{value}' is not a number")

def ReadRays() -> list:
    rays = []
    for index, e in enumerate(ET.parse(SOURCE).getroot().findall("ray")):
        yaw, pitch, rng = (Number(e.get(k), f"ray {index} {k}") for k in ("yaw", "pitch", "range"))
        if rng <= 0: Fail(f"ray {index}: range must be positive")
        rays.append((yaw, pitch, rng))
    if not rays: Fail("Rays.xml has no rays")
    if len(rays) > MAX_RAYS: Fail(f"Rays.xml has {len(rays)} rays, the most is {MAX_RAYS}")
    return rays

def ReadSight() -> list:
    constants, names = [], set()
    for e in ET.parse(SIGHT_SOURCE).getroot().findall("constant"):
        name = e.get("name") or ""
        if not re.fullmatch(r"k_[A-Z][A-Za-z0-9]*", name): Fail(f"constant '{name}': the name must be k_Pascal")
        if name in names: Fail(f"constant '{name}' is repeated")
        names.add(name)
        value = Number(e.get("value"), f"constant {name} value")
        if value <= 0: Fail(f"constant {name}: the value must be positive")
        doc = (e.get("doc") or "").strip()
        if not doc: Fail(f"constant {name} has no doc")
        if ";" in doc: Fail(f"constant {name}: the doc cannot hold ';' (comment rule)")
        constants.append((name, value, doc))
    if not constants: Fail("Sight.xml has no constants")
    return constants

def Literal(value: float) -> str:
    text = repr(value)
    if text.endswith(".0"): text = text[:-2] + ".0"
    return text + "f"

def Generate(rays: list) -> str:
    lines = [HEADER, "export module Views.Raycast.Type:Pattern;", "", "import std;", "",
             "export namespace Views::Raycast::Type::Pattern", "{",
             "    // One ray of the perception pattern, in the frame of the agent. Angles in degrees: yaw from the forward, positive to the left,",
             "    // pitch from the horizontal, positive up. Range in world units.",
             "    struct PatternRay", "    {", "        float Yaw{};", "        float Pitch{};", "        float Range{};", "    };", "",
             "    // Rays of the pattern, in the order of the rows of the table.",
             f"    inline constexpr std::size_t k_PatternRayCount{{ {len(rays)} }};", "",
             f"    inline constexpr std::array<PatternRay, {len(rays)}> k_PatternRays", "    {{"]
    lines += [f"        {{ .Yaw = {Literal(y)}, .Pitch = {Literal(p)}, .Range = {Literal(r)} }}," for y, p, r in rays]
    lines += ["    }};", "}"]
    return "\r\n".join(lines)

def GenerateSight(constants: list) -> str:
    lines = [SIGHT_HEADER, "export module Views.Raycast.Type:Sight;", "", "import std;", "", "export namespace Views::Raycast::Type::Sight", "{"]
    for index, (name, value, doc) in enumerate(constants):
        if index: lines.append("")
        lines += [f"    // {doc}", f"    inline constexpr float {name}{{ {Literal(value)} }};"]
    lines.append("}")
    return "\r\n".join(lines)

def main() -> None:
    parser = argparse.ArgumentParser(description="Generates Views.Raycast.Type:Pattern.")
    parser.add_argument("--check", action="store_true", help="compare with the repo and write nothing")
    check = parser.parse_args().check
    rays = ReadRays()
    constants = ReadSight()
    print(f"[Views] {len(rays)} rays, {len(constants)} sight constants")
    outputs = [(OUT, Generate(rays)), (SIGHT_OUT, GenerateSight(constants))]
    if check:
        different, missing = [], []
        for path, text in outputs:
            CheckBytes(path, text.encode("utf-8"), different, missing, REPO)
        sys.exit(ReportCheck(different, missing, REPO, len(outputs)))
    for path, text in outputs:
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        print(f"  Generated: {os.path.relpath(path, REPO)}")

if __name__ == "__main__":
    main()

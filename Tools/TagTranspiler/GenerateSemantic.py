"""
GenerateSemantic.py
Generates the semantic ids of Artemis as the C++23 module Common.Semantic.Type from
Data/Semantic/Semantic.xml (the single source of the ids) and the hand labels of
Data/Tags/ObjectTags.xml (the tag catalog).

    python Tools/TagTranspiler/GenerateSemantic.py

Writes the primary module in Artemis/1_Shared/Common/Semantic/ and the partitions under Type/:
    Common.Semantic.Type.ixx   primary module (Common/Semantic/), exports the partitions
    SemanticEnum.ixx           :Enum     Group, Function, Lifecycle, Binding, Physics, Relation, Event, Capability
    SemanticSubtype.ixx        :Subtype  one enum per function with subtypes (Subtype::<Function>)
    SemanticCatalog.ixx        :Catalog  labels of the catalog (confidence high, medium or low), sorted by group and name
    SemanticEventKey.ixx       :EventKey keys of the event ring of the engine and their kind (D104, Q85)

Fails (nothing written) when the catalog uses a function or a subtype that Semantic.xml
does not declare, or when Semantic.xml repeats an id. Ids are stable: only append.
Also writes Agent/artemis/semantic.py: the same ids for Python (IntEnum per enum, IntFlag Capability, SUBTYPES per function,
EVENT_KEYS and event_kind for the event keys),
so the fields of the bridge that hold ids (Agent/artemis/bridge_layout.py SEMANTIC_FIELDS) can be named (D135).
"""
import os, sys
import xml.etree.ElementTree as ET

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(SCRIPT_DIR, "..", ".."))
SEMANTIC = os.path.join(REPO, "Data", "Semantic", "Semantic.xml")
CATALOG = os.path.join(REPO, "Data", "Tags", "ObjectTags.xml")
ROOT = os.path.join(REPO, "Artemis", "1_Shared", "Common", "Semantic")
OUT = os.path.join(ROOT, "Type")

RUNTIME_CONFIDENCE = ("high", "medium", "low")
CPP_TYPE = {"uint8": "std::uint8_t", "uint16": "std::uint16_t"}
PY_OUT = os.path.join(REPO, "Agent", "artemis", "semantic.py")
HEADER = "// Generated by Tools/TagTranspiler/GenerateSemantic.py from Data/Semantic/Semantic.xml. Do not edit."

def Fail(message: str) -> None:
    sys.exit("ERROR: " + message)

def Finish(lines: list) -> str:
    # rules.txt: CRLF line endings, no final newline.
    return "\r\n".join(lines).rstrip("\r\n")

def Write(name: str, lines: list, folder: str = OUT) -> None:
    path = os.path.join(folder, name)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(Finish(lines))
    print(f"  Generated: {os.path.relpath(path, REPO)}")

def CheckIds(owner: str, items: list) -> None:
    ids, names = set(), set()
    for name, value in items:
        if value in ids: Fail(f"{owner}: id {value} repeated")
        if name in names: Fail(f"{owner}: name {name} repeated")
        ids.add(value); names.add(name)

def ReadSemantic():
    root = ET.parse(SEMANTIC).getroot()
    enums, functions, flags = [], [], None
    for e in root:
        if e.tag == "enum":
            values = [(v.get("name"), int(v.get("id"))) for v in e.findall("value")]
            CheckIds(e.get("name"), values)
            enums.append({"name": e.get("name"), "type": e.get("type"), "doc": e.get("doc"), "values": values})
            if e.get("name") == "Function":
                for v in e.findall("value"):
                    subs = [(s.get("name"), int(s.get("id"))) for s in v.findall("subtype")]
                    CheckIds("Subtype " + v.get("name"), subs + [("None", 0)])
                    functions.append({"name": v.get("name"), "id": int(v.get("id")), "group": v.get("group"),
                                      "doc": v.get("doc"), "subtypes": subs})
        elif e.tag == "flags":
            bits = [(b.get("name"), int(b.get("index"))) for b in e.findall("bit")]
            CheckIds(e.get("name"), bits)
            flags = {"name": e.get("name"), "type": e.get("type"), "doc": e.get("doc"), "bits": bits}
    groups = {n for n, _ in next(x for x in enums if x["name"] == "Group")["values"]}
    for f in functions:
        if f["group"] not in groups: Fail(f"Function {f['name']}: unknown group {f['group']}")
    return enums, functions, flags

def ReadEventKeys(enums):
    root = ET.parse(SEMANTIC).getroot().find("eventkeys")
    if root is None: Fail("Semantic.xml has no eventkeys")
    kinds = {n for n, _ in next(x for x in enums if x["name"] == "Event")["values"]}
    keys = []
    for k in root.findall("key"):
        value, name, kind = int(k.get("value"), 16), k.get("name"), k.get("kind")
        if kind not in kinds: Fail(f"event key {name}: kind {kind} is not a value of Event")
        keys.append((value, name, kind))
    CheckIds("eventkeys", [(n, v) for v, n, _ in keys])
    keys.sort()
    return int(root.get("statcategory"), 16), keys

def ReadCatalog(functions):
    byName = {f["name"]: f for f in functions}
    labels = []
    for e in ET.parse(CATALOG).getroot().iter("tag"):
        if e.get("confidence") not in RUNTIME_CONFIDENCE or not e.get("function"):
            continue
        group, name, function, subtype = e.get("group"), e.get("name"), e.get("function"), e.get("subtype", "")
        if not group: continue
        f = byName.get(function)
        if f is None: Fail(f"catalog {group} {name}: function {function} not declared in Semantic.xml")
        subId = 0
        if subtype:
            subId = dict(f["subtypes"]).get(subtype)
            if subId is None: Fail(f"catalog {group} {name}: subtype {function}/{subtype} not declared in Semantic.xml")
        facing = e.get("facing", "")
        if facing not in ("", "reversed"): Fail(f"catalog {group} {name}: facing {facing} is not 'reversed'")
        labels.append((group, name, function, subId, facing == "reversed"))
    labels.sort(key=lambda l: (l[0], l[1]))
    for a, b in zip(labels, labels[1:]):
        if (a[0], a[1]) == (b[0], b[1]): Fail(f"catalog: {a[0]} {a[1]} repeated")
    return labels

def NameOf(typeName: str, values: list, indent: str) -> list:
    out = [f"{indent}// return: The name of the value, or an empty view if it is not known.",
           f"{indent}constexpr auto NameOf({typeName} value) -> std::string_view",
           f"{indent}{{", f"{indent}    switch (value)", f"{indent}    {{"]
    for n, _ in values:
        out.append(f"{indent}    case {typeName}::{n}: return \"{n}\";")
    out += [f"{indent}    default: return {{}};", f"{indent}    }}", f"{indent}}}"]
    return out

def GenerateEnum(enums, functions, flags) -> list:
    L = [HEADER, "export module Common.Semantic.Type:Enum;", "", "import std;", "", "export namespace Common::Semantic::Type", "{"]
    for e in enums:
        L.append(f"    // {e['doc']}")
        L += [f"    enum class {e['name']} : {CPP_TYPE[e['type']]}", "    {"]
        for n, v in e["values"]:
            doc = next((f["doc"] for f in functions if f["name"] == n), None) if e["name"] == "Function" else None
            if doc: L.append(f"        // {doc}")
            L.append(f"        {n} = {v},")
        L += ["    };", ""]
    t = CPP_TYPE[flags["type"]]
    L.append(f"    // {flags['doc']}")
    L += [f"    enum class {flags['name']} : {t}", "    {", "        None = 0x0000,"]
    for n, i in flags["bits"]:
        L.append(f"        {n} = 0x{1 << i:04X},")
    L += ["    };", "",
          f"    // Joins two sets of capabilities.",
          f"    constexpr auto operator|({flags['name']} left, {flags['name']} right) -> {flags['name']}",
          "    {", f"        return static_cast<{flags['name']}>(static_cast<{t}>(left) | static_cast<{t}>(right));", "    }", "",
          f"    // return: Whether the set has every bit of the capability.",
          f"    constexpr auto HasCapability({flags['name']} set, {flags['name']} capability) -> bool",
          "    {", f"        return (static_cast<{t}>(set) & static_cast<{t}>(capability)) == static_cast<{t}>(capability);", "    }", ""]
    L += ["    // Returns the group of a function.", "    // note: Every function belongs to one group only, so groups never overlap.",
          "    constexpr auto GroupOf(Function function) -> Group", "    {", "        switch (function)", "        {"]
    for f in functions:
        L.append(f"        case Function::{f['name']}: return Group::{f['group']};")
    L += ["        default: return Group::Unknown;", "        }", "    }"]
    for e in enums:
        L += [""] + NameOf(e["name"], e["values"], "    ")
    L.append("}")
    return L

def GenerateSubtype(functions) -> list:
    L = [HEADER, "export module Common.Semantic.Type:Subtype;", "", "import :Enum;", "import std;", "",
         "export namespace Common::Semantic::Type::Subtype", "{"]
    withSubs = [f for f in functions if f["subtypes"]]
    for f in withSubs:
        L += [f"    // Subtypes of Function::{f['name']}.", f"    enum class {f['name']} : std::uint8_t", "    {", "        None = 0,"]
        for n, v in f["subtypes"]:
            L.append(f"        {n} = {v},")
        L += ["    };", ""]
    L += ["    // Returns the name of the subtype of a function.",
          "    // param subtype: Value of the subtype enum of the function (Subtype::<Function>).",
          "    // return: The name, or an empty view for None or an unknown value.",
          "    constexpr auto NameOf(Function function, std::uint8_t subtype) -> std::string_view",
          "    {", "        switch (function)", "        {"]
    for f in withSubs:
        L += [f"        case Function::{f['name']}:", "            switch (subtype)", "            {"]
        for n, v in f["subtypes"]:
            L.append(f"            case {v}: return \"{n}\";")
        L += ["            default: return {};", "            }"]
    L += ["        default: return {};", "        }", "    }", "}"]
    return L

def GenerateCatalog(labels) -> list:
    L = [HEADER, "export module Common.Semantic.Type:Catalog;", "", "import :Enum;", "import std;", "",
         "export namespace Common::Semantic::Type::Catalog", "{",
         "    // Hand label of one object tag, from Data/Tags/ObjectTags.xml (confidence high, medium or low).",
         "    // note: The classifier uses it before the multiplayer object kind of the tag and the kind default (Ignore/Semantizacion/05, section 3).",
         "    struct TagLabel", "    {",
         "        // Four letter group of the tag (fourcc).",
         "        std::string_view Group{};", "        std::string_view TagName{};", "        Function Function{};", "",
         "        // Value of the subtype enum of the function (Subtype::<Function>). 0 is None.",
         "        std::uint8_t Subtype{};", "",
         "        // The Forward of the model points against the meaning of the function (facing=\"reversed\" in the catalog).",
         "        // note: A OneWay Barrier with it passes along -Forward (the ff_one_way_door tags).",
         "        bool IsFacingReversed{};", "    };", "",
         "    // Labels sorted by group and tag name.",
         f"    inline constexpr std::array<TagLabel, {len(labels)}> k_TagLabels", "    {{"]
    for g, n, f, s, r in labels:
        cn = n.replace("\\", "\\\\").replace('"', '\\"')
        reversed_ = ", .IsFacingReversed = true" if r else ""
        L.append(f"        {{ .Group = \"{g}\", .TagName = \"{cn}\", .Function = Function::{f}, .Subtype = {s}{reversed_} }},")
    L += ["    }};", "",
          "    // Finds the label of an object tag.",
          "    // param group: Four letter group of the tag (fourcc).",
          "    // return: The label, or nullptr when the catalog does not label the tag.",
          "    constexpr auto FindTagLabel(std::string_view group, std::string_view tagName) -> const TagLabel*",
          "    {", "        std::size_t low{ 0 };", "        std::size_t high{ k_TagLabels.size() };", "",
          "        while (low < high)", "        {",
          "            const std::size_t middle{ low + (high - low) / 2 };",
          "            const TagLabel& label{ k_TagLabels[middle] };", "",
          "            const int order{ (label.Group != group) ? label.Group.compare(group) : label.TagName.compare(tagName) };", "",
          "            if (order == 0) return &label;", "",
          "            if (order < 0)", "            {", "                low = middle + 1;", "            }",
          "            else", "            {", "                high = middle;", "            }",
          "        }", "", "        return nullptr;", "    }", "}"]
    return L

def GenerateEventKey(statCategory, keys) -> list:
    L = [HEADER, "export module Common.Semantic.Type:EventKey;", "", "import :Enum;", "import std;", "",
         "export namespace Common::Semantic::Type::EventKey", "{",
         "    // One key of the event ring of the engine (D104) and the kind of event it is.",
         "    struct EventKeyLabel", "    {", "        std::uint32_t Key{};", "        std::string_view Name{};", "        Event Kind{};", "    };", "",
         "    // Category (key >> 16) of the statistics keys. Unlisted keys of it are Stat, the rest Medal.",
         f"    inline constexpr std::uint32_t k_StatCategory{{ 0x{statCategory:02X} }};", "",
         "    // Labels sorted by key.",
         f"    inline constexpr std::array<EventKeyLabel, {len(keys)}> k_EventKeyLabels", "    {{"]
    for v, n, k in keys:
        L.append(f"        {{ .Key = 0x{v:06X}, .Name = \"{n}\", .Kind = Event::{k} }},")
    L += ["    }};", "",
          "    // return: The label of the key, or nullptr when it is not listed.",
          "    constexpr auto FindEventKey(std::uint32_t key) -> const EventKeyLabel*",
          "    {",
          "        const auto found{ std::lower_bound(k_EventKeyLabels.begin(), k_EventKeyLabels.end(), key,",
          "            [](const EventKeyLabel& label, std::uint32_t value) { return label.Key < value; }) };",
          "        return (found != k_EventKeyLabels.end() && found->Key == key) ? &*found : nullptr;",
          "    }", "",
          "    // return: The kind of the key. Unlisted keys: Stat in the statistics category, Medal otherwise.",
          "    constexpr auto KindOf(std::uint32_t key) -> Event",
          "    {",
          "        if (const EventKeyLabel* label{ FindEventKey(key) }) return label->Kind;",
          "        return ((key >> 16) == k_StatCategory) ? Event::Stat : Event::Medal;",
          "    }", "}"]
    return L

def GeneratePython(enums, functions, flags, statCategory, keys) -> list:
    L = ['"""Generated by Tools/TagTranspiler/GenerateSemantic.py from Data/Semantic/Semantic.xml. Do not edit.', "",
         "Semantic ids of Artemis (stable: only appended). The same values as Common.Semantic.Type in C++.", '"""', "import enum"]
    for e in enums:
        L += ["", "", f"class {e['name']}(enum.IntEnum):", f'    """{e["doc"]}"""']
        # note: Python cannot name a member None, so it is NONE there.
        L += [f"    {'NONE' if n == 'None' else n} = {v}" for n, v in e["values"]]
    L += ["", "", f"class {flags['name']}(enum.IntFlag):", f'    """{flags["doc"]}"""', "    NONE = 0"]
    L += [f"    {n} = {1 << i:#06x}" for n, i in flags["bits"]]
    L += ["", "", "# Subtype ids of each function with subtypes (0 is None).", "SUBTYPES = {"]
    for f in functions:
        if f["subtypes"]:
            L.append(f"    Function.{f['name']}: {{" + ", ".join(f"{i}: {n!r}" for n, i in f["subtypes"]) + "},")
    L.append("}")
    L += ["", "", "# Keys of the event ring of the engine (D104): key -> (name, kind).", "EVENT_KEYS = {"]
    L += [f"    0x{v:06X}: ({n!r}, Event.{k})," for v, n, k in keys]
    L += ["}", f"STAT_CATEGORY = 0x{statCategory:02X}", "", "",
          "def event_kind(key: int) -> Event:",
          '    """Kind of an event key. Unlisted keys: Stat in the statistics category, Medal otherwise."""',
          "    label = EVENT_KEYS.get(key)",
          "    if label is not None:",
          "        return label[1]",
          "    return Event.Stat if (key >> 16) == STAT_CATEGORY else Event.Medal"]
    return L

def main() -> None:
    enums, functions, flags = ReadSemantic()
    statCategory, keys = ReadEventKeys(enums)
    labels = ReadCatalog(functions)
    os.makedirs(OUT, exist_ok=True)
    print(f"[Semantic] {len(functions)} functions, {sum(len(f['subtypes']) for f in functions)} subtypes, {len(labels)} catalog labels")
    Write("Common.Semantic.Type.ixx", [HEADER, "export module Common.Semantic.Type;", "",
                                       "export import :Enum;", "export import :Subtype;", "export import :Catalog;",
                                       "export import :EventKey;"], ROOT)
    Write("SemanticEnum.ixx", GenerateEnum(enums, functions, flags))
    Write("SemanticSubtype.ixx", GenerateSubtype(functions))
    Write("SemanticCatalog.ixx", GenerateCatalog(labels))
    Write("SemanticEventKey.ixx", GenerateEventKey(statCategory, keys))
    os.makedirs(os.path.dirname(PY_OUT), exist_ok=True)
    with open(PY_OUT, "w", encoding="utf-8", newline="") as f:
        f.write(Finish(GeneratePython(enums, functions, flags, statCategory, keys)) + "\r\n")
    print(f"  Generated: {os.path.relpath(PY_OUT, REPO)}")

if __name__ == "__main__":
    main()

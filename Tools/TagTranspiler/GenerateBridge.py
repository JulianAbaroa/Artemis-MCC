"""
GenerateBridge.py
Generates both sides of the shared memory of the bridge between Artemis and Python (D65, D135) from Data/Bridge/Bridge.xml,
the single source of its layout.

    python Tools/TagTranspiler/GenerateBridge.py
    python Tools/TagTranspiler/GenerateBridge.py --check    # compare with the repo, write nothing (exit 0 equal, 1 not)

Writes:
    Artemis/1_Shared/Contract/Contract.Bridge.Type.ixx                           Module Contract.Bridge.Type (namespace Contract::Bridge::Type). POD structs,
                                                                        enums and constants, with a static_assert for every size and offset.
    Agent/artemis/bridge_layout.py                                      numpy dtypes with the same offsets, enums, constants,
                                                                        OFFSETS of the region fields and the LayoutHash.

The layout is computed here with natural alignment (the alignment of a field is its size, or the largest of a struct, raised by
align=), the same rule MSVC follows on x64, so the static_asserts prove that the compiler agrees. LayoutHash (FNV-1a 64 of the
computed layout) changes with any change of a field, a type, an offset or a constant: Python refuses a region with another hash.
Fails (nothing written) on an unknown type, enum or constant, or a repeated name.
"""
import argparse, json
import os, sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from Common import CheckBytes, ReportCheck

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(SCRIPT_DIR, "..", ".."))
SOURCE = os.path.join(REPO, "Data", "Bridge", "Bridge.xml")
CPP_OUT = os.path.join(REPO, "Artemis", "1_Shared", "Contract", "Contract.Bridge.Type.ixx")
PY_OUT = os.path.join(REPO, "Agent", "artemis", "bridge_layout.py")

HEADER = "Generated by Tools/TagTranspiler/GenerateBridge.py from Data/Bridge/Bridge.xml. Do not edit."
PRIMITIVES = {
    "u8": (1, "std::uint8_t", "u1"), "u16": (2, "std::uint16_t", "<u2"), "u32": (4, "std::uint32_t", "<u4"),
    "u64": (8, "std::uint64_t", "<u8"), "i8": (1, "std::int8_t", "i1"), "i16": (2, "std::int16_t", "<i2"), "f32": (4, "float", "<f4"),
}


def Fail(message):
    sys.exit("ERROR: " + message)


def Up(value, align):
    return (value + align - 1) // align * align


def Snake(name):
    out = ""
    for i, c in enumerate(name):
        if c.isupper() and i > 0 and (not name[i - 1].isupper() or (i + 1 < len(name) and name[i + 1].islower())):
            out += "_"
        out += c.upper()
    return out


def CppConst(name):
    return "k_" + (name if name.startswith("Bridge") else "Bridge" + name)


def Read():
    root = ET.parse(SOURCE).getroot()
    model = {"version": int(root.get("version")), "consts": [], "strings": [], "enums": [], "structs": []}
    names = set()

    def Claim(name):
        if name in names: Fail(f"name {name} repeated")
        names.add(name)

    for e in root:
        if e.tag == "const":
            Claim(e.get("name"))
            model["consts"].append({"name": e.get("name"), "value": int(e.get("value"), 0), "doc": e.get("doc"), "type": e.get("type"),
                                    "cpp": e.get("cpp", "true") != "false", "owner": e.get("owner")})
        elif e.tag == "string":
            Claim(e.get("name"))
            model["strings"].append({"name": e.get("name"), "value": e.get("value"), "doc": e.get("doc")})
        elif e.tag in ("enum", "flags"):
            Claim(e.get("name"))
            if e.tag == "enum":
                values = [(v.get("name"), int(v.get("id")), v.get("doc")) for v in e.findall("value")]
            else:
                values = [(b.get("name"), 1 << int(b.get("index")), b.get("doc")) for b in e.findall("bit")]
            if len({v[1] for v in values}) != len(values): Fail(f"{e.get('name')}: repeated value")
            model["enums"].append({"name": e.get("name"), "type": e.get("type"), "doc": e.get("doc"), "values": values,
                                   "isFlags": e.tag == "flags"})
        elif e.tag == "struct":
            Claim(e.get("name"))
            fields = []
            for f in e.findall("field"):
                if any(x["name"] == f.get("name") for x in fields): Fail(f"{e.get('name')}.{f.get('name')} repeated")
                fields.append({k: f.get(k) for k in ("name", "type", "count", "align", "enum", "semantic", "doc")})
            model["structs"].append({"name": e.get("name"), "align": int(e.get("align", "1")), "doc": e.get("doc"),
                                     "fields": fields})
    return model


def Layout(model):
    consts = {c["name"]: c["value"] for c in model["consts"]}
    enums = {e["name"]: e for e in model["enums"]}
    structs = {}
    for s in model["structs"]:
        offset, align = 0, s["align"]
        for f in s["fields"]:
            if f["type"] in PRIMITIVES:
                size = PRIMITIVES[f["type"]][0]
                falign = size
            elif f["type"] in structs:
                size, falign = structs[f["type"]]["size"], structs[f["type"]]["align"]
            else:
                Fail(f"{s['name']}.{f['name']}: unknown type {f['type']}")
            if f["enum"] and f["enum"] not in enums: Fail(f"{s['name']}.{f['name']}: unknown enum {f['enum']}")
            if f["enum"] and PRIMITIVES[enums[f["enum"]]["type"]] != PRIMITIVES[f["type"]]:
                Fail(f"{s['name']}.{f['name']}: type {f['type']} is not the type of {f['enum']}")
            count = f["count"]
            f["n"] = 1 if count is None else (int(count) if count.isdigit() else consts.get(count))
            if f["n"] is None: Fail(f"{s['name']}.{f['name']}: unknown count {count}")
            falign = max(falign, int(f["align"] or 1))
            offset = Up(offset, falign)
            f["offset"], f["elementSize"] = offset, size
            offset += size * f["n"]
            align = max(align, falign)
        s["size"], s["align"] = Up(offset, align), align
        structs[s["name"]] = s
    return structs


def Hash(model, structs):
    text = f"v{model['version']};"
    text += "".join(f"c:{c['name']}={c['value']};" for c in model["consts"])
    text += "".join(f"s:{c['name']}={c['value']};" for c in model["strings"])
    text += "".join(f"e:{e['name']}:{e['type']}:" + ",".join(f"{n}={v}" for n, v, _ in e["values"]) + ";" for e in model["enums"])
    for s in structs.values():
        text += f"t:{s['name']}:{s['size']}:{s['align']}:"
        text += ",".join(f"{f['name']}:{f['type']}:{f['offset']}:{f['n']}:{f['enum'] or ''}" for f in s["fields"]) + ";"
    value = 0xCBF29CE484222325
    for byte in text.encode("ascii"):
        value = ((value ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return value


def LayoutJson(model, structs, hash):
    """The layout of every struct as compact JSON: a TickDump embeds it so an old dump stays readable after Bridge.xml changes
    (D151). Field: [name, type, offset, count, enum]; type is a key of "primitives" (numpy format) or the name of a struct listed
    earlier (the structs come in dependency order)."""
    data = {"version": model["version"], "hash": f"0x{hash:016X}", "primitives": {k: v[2] for k, v in PRIMITIVES.items()},
            "structs": [{"name": s["name"], "size": s["size"], "align": s["align"],
                         "fields": [[f["name"], f["type"], f["offset"], f["n"], f["enum"] or ""] for f in s["fields"]]}
                        for s in structs.values()]}
    text = json.dumps(data, separators=(",", ":"))
    # note: MSVC joins the pieces of a string literal up to about 64 KB, and ')json"' would end a raw piece early.
    if len(text) > 60000: Fail(f"layout JSON of {len(text)} bytes: split k_BridgeLayoutJson before it passes the MSVC limit")
    if ')json"' in text: Fail("layout JSON contains the raw string delimiter")
    return text


def Comment(doc, indent):
    return [f"{indent}// {doc}"] if doc else []


def Cpp(model, structs, hash, layout_json):
    enums = {e["name"]: e for e in model["enums"]}
    owners = [c for c in model["consts"] if c["owner"]]
    # note: offsetof is a macro, so it comes from the global module fragment and not from import std.
    L = ["// " + HEADER, "module;", "", "#include <cstddef>", "", "export module Contract.Bridge.Type;", ""]
    L += sorted({f"import {c['owner'].split(':')[0]};" for c in owners})
    L += ["import std;", ""]
    if owners:
        L += ["namespace", "{"]
        L += [f"    using {c['owner'].split(':')[0].replace('.', '::')}::{c['owner'].split(':')[1]};" for c in owners]
        L += ["}", ""]
    L += ["export namespace Contract::Bridge::Type", "{"]
    L += ["    // Version of the layout. Raised by hand when the meaning of a field changes without changing the layout.",
          f"    inline constexpr std::uint32_t k_BridgeLayoutVersion{{ {model['version']} }};", "",
          "    // FNV-1a 64 of the computed layout. Python compares it with the hash of its generated module.",
          f"    inline constexpr std::uint64_t k_BridgeLayoutHash{{ 0x{hash:016X} }};", ""]
    # note: Raw string pieces of 2000 characters: MSVC caps one string literal at 16380 bytes.
    pieces = [layout_json[i:i + 2000] for i in range(0, len(layout_json), 2000)]
    L += ["    // Layout of every struct as JSON (GenerateBridge.py LayoutJson). Each TickDump embeds it (D151).",
          "    inline constexpr std::string_view k_BridgeLayoutJson{"] + [f'        R"json({p})json"' for p in pieces] + ["    };", ""]
    for c in model["consts"]:
        if not c["cpp"]: continue
        if c["owner"]:
            name = c["owner"].split(":")[1]
            value = f"0x{c['value']:X}" if c["value"] > 255 else str(c["value"])
            L += [f"    static_assert({name} == {value}, \"Bridge.xml {c['name']} must match {name}.\");", ""]
            continue
        L += Comment(c["doc"], "    ")
        t = PRIMITIVES[c["type"]][1] if c["type"] else ("std::uint32_t" if c["value"] <= 0xFFFFFFFF else "std::uint64_t")
        L += [f"    inline constexpr {t} {CppConst(c['name'])}{{ 0x{c['value']:X} }};" if c["value"] > 255 else
              f"    inline constexpr {t} {CppConst(c['name'])}{{ {c['value']} }};", ""]
    for c in model["strings"]:
        L += Comment(c["doc"], "    ")
        value = c["value"].replace("\\", "\\\\")
        L += [f"    inline constexpr std::string_view {CppConst(c['name'])}{{ \"{value}\" }};", ""]
    for e in model["enums"]:
        L += Comment(e["doc"], "    ")
        L += [f"    enum class {e['name']} : {PRIMITIVES[e['type']][1]}", "    {"]
        for n, v, doc in e["values"]:
            L += Comment(doc, "        ")
            L.append(f"        {n} = 0x{v:X}," if e["isFlags"] else f"        {n} = {v},")
        L += ["    };", ""]
    consts = {c["name"]: c for c in model["consts"]}
    for s in structs.values():
        L += Comment(s["doc"], "    ")
        L += [f"    struct alignas({s['align']}) {s['name']}" if s["align"] > 1 and s["align"] != Natural(s, structs) else
              f"    struct {s['name']}", "    {"]
        for f in s["fields"]:
            L += Comment(f["doc"], "        ")
            if f["type"] in PRIMITIVES:
                t = PRIMITIVES[f["type"]][1]
                if f["enum"] and not enums[f["enum"]]["isFlags"]: t = f["enum"]
            else:
                t = f["type"]
            if f["count"]:
                c = consts.get(f["count"])
                size = (c["owner"].split(":")[1] if c["owner"] else CppConst(c["name"])) if c else f["count"]
                t = f"std::array<{t}, {size}>"
            prefix = f"alignas({f['align']}) " if f["align"] else ""
            L.append(f"        {prefix}{t} {f['name']}{{}};")
        L += ["    };", ""]
    L += ["    // The layout above, as computed by the generator. A failure means the compiler and Bridge.xml disagree."]
    for s in structs.values():
        L.append(f"    static_assert(sizeof({s['name']}) == {s['size']} && alignof({s['name']}) == {s['align']});")
        L.append(f"    static_assert(std::is_trivially_copyable_v<{s['name']}> && std::is_standard_layout_v<{s['name']}>);")
        for f in s["fields"]:
            L.append(f"    static_assert(offsetof({s['name']}, {f['name']}) == {f['offset']});")
    L.append("}")
    return L


def Natural(struct, structs):
    align = 1
    for f in struct["fields"]:
        a = PRIMITIVES[f["type"]][0] if f["type"] in PRIMITIVES else structs[f["type"]]["align"]
        align = max(align, a, int(f["align"] or 1))
    return align


def Offsets(structs, name, base, prefix, out):
    for f in structs[name]["fields"]:
        path = f"{prefix}{f['name']}"
        out.append((path, base + f["offset"]))
        if f["type"] in structs and f["n"] == 1:
            Offsets(structs, f["type"], base + f["offset"], path + ".", out)


def Python(model, structs, hash):
    L = ['"""' + HEADER, "", "Layout of the shared memory of the bridge (D135): constants, enums, numpy dtypes with the offsets of the C++",
         "structs, and OFFSETS of the region fields (dotted paths, arrays at their first element).", '"""',
         "import enum", "", "import numpy as np", "",
         f"LAYOUT_VERSION = {model['version']}", f"LAYOUT_HASH = 0x{hash:016X}"]
    for c in model["consts"]:
        L.append(f"{Snake(c['name'])} = {c['value']:#x}" if c["value"] > 255 else f"{Snake(c['name'])} = {c['value']}")
    for c in model["strings"]:
        L.append(f"{Snake(c['name'])} = {c['value']!r}")
    for e in model["enums"]:
        L += ["", "", f"class {e['name']}(enum.{'IntFlag' if e['isFlags'] else 'IntEnum'}):", f'    """{e["doc"]}"""']
        L += [f"    {n} = {v:#x}" if e["isFlags"] else f"    {n} = {v}" for n, v, _ in e["values"]]
    L += ["", ""]
    for s in structs.values():
        formats = []
        for f in s["fields"]:
            base = PRIMITIVES[f["type"]][2] if f["type"] in PRIMITIVES else f["type"]
            quoted = f"'{base}'" if f["type"] in PRIMITIVES else base
            formats.append(f"({quoted}, ({f['n']},))" if f["count"] else quoted)
        L.append(f"# {s['doc']}")
        L.append(f"{s['name']} = np.dtype({{")
        L.append(f"    'names': {[f['name'] for f in s['fields']]!r},")
        L.append(f"    'formats': [{', '.join(formats)}],")
        L.append(f"    'offsets': {[f['offset'] for f in s['fields']]!r},")
        L.append(f"    'itemsize': {s['size']},")
        L.append("})")
        L.append("")
    sem = [(s["name"], f["name"], f["semantic"]) for s in structs.values() for f in s["fields"] if f["semantic"]]
    L += ["# Fields that hold an id of Data/Semantic/Semantic.xml or of Common (artemis.semantic has the Semantic.xml ones).",
          "SEMANTIC_FIELDS = {"] + [f"    ({a!r}, {b!r}): {c!r}," for a, b, c in sem] + ["}", ""]
    out = []
    Offsets(structs, "BridgeRegion", 0, "", out)
    L += ["# Byte offset of each field of the region.", "OFFSETS = {"] + [f"    {p!r}: {o}," for p, o in out] + ["}", ""]
    L.append(f"REGION_SIZE = {structs['BridgeRegion']['size']}")
    return L


# --check: (different, missing) while comparing instead of writing; None when writing.
CHECK = None


def Write(path, lines, crlf_final):
    text = "\r\n".join(lines).rstrip("\r\n") + ("\r\n" if crlf_final else "")
    if CHECK is not None:
        CheckBytes(path, text.encode("utf-8"), CHECK[0], CHECK[1], REPO)
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print(f"  Generated: {os.path.relpath(path, REPO)}")


def main():
    global CHECK
    parser = argparse.ArgumentParser(description="Generates both sides of the bridge layout from Data/Bridge/Bridge.xml.")
    parser.add_argument("--check", action="store_true", help="compare with the repo and write nothing")
    args = parser.parse_args()
    if args.check:
        CHECK = ([], [])
    model = Read()
    structs = Layout(model)
    hash = Hash(model, structs)
    print(f"[Bridge] {len(structs)} structs, region {structs['BridgeRegion']['size']} bytes, hash 0x{hash:016X}")
    Write(CPP_OUT, Cpp(model, structs, hash, LayoutJson(model, structs, hash)), False)
    Write(PY_OUT, Python(model, structs, hash), True)
    if CHECK is not None:
        sys.exit(ReportCheck(sorted(CHECK[0]), sorted(CHECK[1]), REPO, 2))


if __name__ == "__main__":
    main()

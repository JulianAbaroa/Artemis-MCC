import re, sys

SYSTEM_DLL = r"C:\\Windows\\System32\\wtsapi32"

def parse_dumpbin(path):
    names = []
    in_table = False
    for line in open(path, encoding="utf-8", errors="ignore"):
        if re.search(r"ordinal\s+hint\s+RVA\s+name", line):
            in_table = True
            continue
        if in_table:
            # Rows look like:  1    0   0001AB20 WTSCloseServer
            m = re.match(r"\s*\d+\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+(\w+)", line)
            if m:
                names.append(m.group(1))
            elif line.strip() == "" and names:
                break
    return names

def generate(names):
    out = [
        "#pragma once\n\n",
        "// Proxy export forwarders for wtsapi32.dll.\n",
        "// Auto-generated by GenerateProxyExports.py from the export table of\n",
        "// the system wtsapi32.dll (Windows). Do not edit by hand; regenerate.\n\n",
    ]
    for n in names:
        out.append(
            f'#pragma comment(linker, "/export:{n}='
            f'{SYSTEM_DLL}.{n}")\n'
        )
    open("ProxyExports.h", "w").writelines(out)
    print(f"Generated ProxyExports.h with {len(names)} exports.")

if __name__ == "__main__":
    generate(parse_dumpbin(sys.argv[1] if len(sys.argv) > 1 else "exports.txt"))
"""
GenerateTags.py
Processes one or more Assembly XML files and generates C++23 Module interfaces (.ixx).

Usage, a single XML:
    python GenerateTags.py phmo.xml

Usage, full directory of plugins:
    python GenerateTags.py ".../Assembly/Plugins/ReachMCC"
"""
import sys, os, re

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, SCRIPT_DIR)
from Common import XmlBaseName
import GenerateOffset
import GenerateStructure
import GenerateObject

_DOMAIN_ROOT = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "Artemis", "Core", "Domain", "1_Map"))

# "Tags" is a purely visual grouping folder: it never appears in a module
# name or a namespace. Each tag then gets its own Type/State/System, exactly
# like the other layers' concept folders (Classifier, Collidable, etc.).
TAGS_ROOT = os.path.join(_DOMAIN_ROOT, "Tag")

def GenerateSystemAggregate(prefix: str, xmlSource: str, tagRoot: str) -> None:
    """
    placeholder
    """
    lines = []
    lines.append(f"// Auto-generated by TagTranspiler (GenerateTags.py)")
    lines.append(f"// Source XML: {xmlSource}")
    lines.append(f"")
    lines.append(f"export module Map.Tag.System:{prefix};")
    lines.append(f"")
    lines.append(f"export import :{prefix}.Descriptor;")
    lines.append(f"")

    outPath = os.path.join(tagRoot, f"Map.Tag.System.{prefix}.ixx")
    with open(outPath, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"  Generated Module:    {outPath}")


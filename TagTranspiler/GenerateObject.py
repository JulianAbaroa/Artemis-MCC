"""
GenerateObject.py
Generates the {Group}:Object and {Group}:Descriptor C++23 module partitions from an XML plugin.
"""
import xml.etree.ElementTree as ET
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from Common import XmlBaseName, BuildBlockTree, BlockNode

def GenerateInflatedStructs(nodes: list[BlockNode], lines: list[str]) -> None:
    """Generates in-memory inflated structs (with vectors), children first."""
    for node in nodes:
        if node.HasChildren:
            GenerateInflatedStructs(node.Children, lines)
            lines.append(f"    struct {node.ObjectStruct} : public {node.DiskStruct}")
            lines.append("    {")
            for child in node.Children:
                lines.append(f"        std::vector<{child.VectorElementType}> {child.FieldName};")
            lines.append("    };")
            lines.append("")

def GenerateObjectHeader(prefix: str, rootNodes: list[BlockNode], xmlSource: str) -> str:
    lines = []
    lines.append(f"// Auto-generated by TagTranspiler (GenerateObject.py)")
    lines.append(f"// Source XML: {os.path.basename(xmlSource)}")
    lines.append(f"")
    lines.append(f"export module Map.Tag.Type:{prefix}.Object;")
    lines.append(f"")
    lines.append(f"import :{prefix}.Structure;")
    lines.append(f"import std;")
    lines.append(f"")
    lines.append(f"namespace")
    lines.append("{")
    lines.append(f"    using namespace Map::Tag::Type::{prefix}::Structure;")
    lines.append("}")
    lines.append(f"")
    lines.append(f"export namespace Map::Tag::Type::{prefix}::Object")
    lines.append(f"{{")

    GenerateInflatedStructs(rootNodes, lines)

    lines.append(f"    struct {prefix}Object")
    lines.append("    {")
    lines.append(f"        std::string  TagName;")
    lines.append(f"        {prefix}Data Data;")
    lines.append(f"")
    for node in rootNodes:
        lines.append(f"        std::vector<{node.VectorElementType}> {node.FieldName};")
    lines.append("    };")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)

def GenerateReadCalls(nodes: list[BlockNode], reader: str, file: str,
                      dataExpr: str, objectExpr: str, indent: str,
                      lines: list[str], depth: int = 0) -> None:
    for node in nodes:
        if not node.HasChildren:
            lines.append(
                f"{indent}{objectExpr}.{node.FieldName} = "
                f"{reader}.template ReadBlock<{node.DiskStruct}>"
                f"({file}, {dataExpr}.{node.FieldName});"
            )
        else:
            diskVar  = f"disk_{node.Pascal}_{depth}"
            entryVar = f"entry_{node.Pascal}_{depth}"
            loopVar  = f"diskEntry_{depth}"

            lines.append(f"{indent}{{")
            lines.append(
                f"{indent}    auto {diskVar} = "
                f"{reader}.template ReadBlock<{node.DiskStruct}>"
                f"({file}, {dataExpr}.{node.FieldName});"
            )
            lines.append(f"{indent}    {objectExpr}.{node.FieldName}.reserve({diskVar}.size());")
            lines.append(f"{indent}    for (auto& {loopVar} : {diskVar})")
            lines.append(f"{indent}    {{")
            lines.append(
                f"{indent}        {node.ObjectStruct} {entryVar}"
                f"{{static_cast<{node.DiskStruct}>({loopVar})}};"
            )
            GenerateReadCalls(
                node.Children, reader, file,
                dataExpr=loopVar, objectExpr=entryVar,
                indent=indent + "        ", lines=lines, depth=depth + 1
            )
            lines.append(f"{indent}        {objectExpr}.{node.FieldName}.push_back({entryVar});")
            lines.append(f"{indent}    }}")
            lines.append(f"{indent}}}")

def GenerateDescriptorHeader(prefix: str, rootNodes: list[BlockNode], xmlSource: str) -> str:
    lines = []
    lines.append(f"// Auto-generated by TagTranspiler (GenerateObject.py)")
    lines.append(f"// Source XML: {os.path.basename(xmlSource)}")
    lines.append(f"")
    lines.append(f"export module Map.Tag.System:{prefix}.Descriptor;")
    lines.append(f"")
    lines.append(f"import Map.Tag.Type;")
    lines.append(f"import Map.Reader.Type;")
    lines.append(f"import Map.Reader.System;")
    lines.append(f"import std;")
    lines.append(f"")
    lines.append(f"namespace")
    lines.append("{")
    lines.append(f"    using namespace Map::Tag::Type::{prefix}::Structure;")
    lines.append(f"    using namespace Map::Tag::Type::{prefix}::Object;")
    lines.append(f"    namespace MapMagic = Map::Reader::Type::Magic;")
    lines.append("}")
    lines.append(f"")
    lines.append(f"export namespace Map::Reader::System")
    lines.append(f"{{")
    lines.append(f"    template <>")
    lines.append(f"    struct GroupDescriptor<{prefix}Object>")
    lines.append(f"    {{")
    lines.append(f"        using DataType = {prefix}Data;")
    lines.append(f"        static constexpr std::uint32_t Magic = MapMagic::Tag::k_{prefix};")
    lines.append(f"")
    lines.append(f"        template <typename TReader>")
    lines.append(f"        static void ReadBlocks(")
    lines.append(f"            std::ifstream& file,")
    lines.append(f"            const TReader& reader,")
    lines.append(f"            {prefix}Object& obj)")
    lines.append(f"        {{")
    GenerateReadCalls(
        rootNodes, reader="reader", file="file",
        dataExpr="obj.Data", objectExpr="obj",
        indent="            ", lines=lines, depth=0
    )
    lines.append(f"        }}")
    lines.append(f"    }};")
    lines.append(f"}}")
    lines.append(f"")
    return "\n".join(lines)

def Generate(xmlPath: str, typeOutDir: str, systemOutDir: str) -> None:
    """
    Object.ixx     -> Map.{prefix}.Type partition   -> typeOutDir
    {prefix}.System.ixx -> Map.{prefix}.System, a standalone primary module (no partition) -> systemOutDir
    """
    tree      = ET.parse(xmlPath)
    root      = tree.getroot()
    prefix    = XmlBaseName(xmlPath)
    xmlSource = os.path.basename(xmlPath)
    rootNodes = BuildBlockTree(root, prefix)

    os.makedirs(typeOutDir, exist_ok=True)
    os.makedirs(systemOutDir, exist_ok=True)

    objectPath = os.path.join(typeOutDir, f"{prefix}Object.ixx")
    systemPath = os.path.join(systemOutDir, f"{prefix}Descriptor.ixx")

    with open(objectPath, "w", encoding="utf-8") as f:
        f.write(GenerateObjectHeader(prefix, rootNodes, xmlSource))
    with open(systemPath, "w", encoding="utf-8") as f:
        f.write(GenerateDescriptorHeader(prefix, rootNodes, xmlSource))
    print(f"  Generated Partition: {objectPath}")
    print(f"  Generated Module:    {systemPath}")

if __name__ == "__main__":
    if len(sys.argv) < 4:
        print("Usage: python GenerateObject.py input.xml type_output_dir/ system_output_dir/")
        sys.exit(1)
    Generate(sys.argv[1], sys.argv[2], sys.argv[3])
"""
GenerateCatalog.py
Regenerates the root of Domain/1_Map/Tag/ from whatever tag folders exist on
disk: the three umbrella modules (Map.Tag.Type.ixx, Map.Tag.System.ixx,
Map.Tag.State.ixx) and Map.TagCatalog.ixx (Map.Tag.State:Catalog).

This is the part of 1_Map/Tag/... that section 6.5 of the handoff flagged as
"la unica parte no 100% automatica": adding tag #20 used to mean hand-editing
four files. This module makes all four fully derived from the set of tag
folders present under Tag/, so GenerateTags.py can call it after every run
(single XML or full directory) and the root always reflects reality --- not
just whatever was processed in that invocation.

A folder under Tag/ counts as a tag if it directly contains a
Map.Tag.Type.<Name>.ixx generated by GenerateTags.py (GenerateTypeAggregate).
That file's existence is exactly the signal that GenerateTags.py finished
generating that tag's Type/State/System, so it's a safe discovery marker ---
no XML re-parsing needed here.
"""
import os


def DiscoverTags(tagsRoot: str) -> list[str]:
    """Returns tag prefixes (folder names) that have been generated under
    tagsRoot, sorted alphabetically -- same order the hand-written files
    used before this was automated."""
    prefixes = []
    if not os.path.isdir(tagsRoot):
        return prefixes

    for entry in os.listdir(tagsRoot):
        entryPath = os.path.join(tagsRoot, entry)
        if not os.path.isdir(entryPath):
            continue
        marker = os.path.join(entryPath, f"Map.Tag.Type.{entry}.ixx")
        if os.path.isfile(marker):
            prefixes.append(entry)

    return sorted(prefixes)


def _WriteIfChanged(outPath: str, content: str) -> bool:
    if os.path.isfile(outPath):
        with open(outPath, "r", encoding="utf-8") as f:
            if f.read() == content:
                return False
    with open(outPath, "w", encoding="utf-8") as f:
        f.write(content)
    return True


def GenerateTypeUmbrella(prefixes: list[str], tagsRoot: str) -> str:
    lines = []
    lines.append(f"// Auto-generated by TagTranspiler (GenerateCatalog.py)")
    lines.append(f"")
    lines.append(f"export module Map.Tag.Type;")
    lines.append(f"")
    for prefix in prefixes:
        lines.append(f"export import :{prefix};")
    content = "\n".join(lines) + "\n"

    outPath = os.path.join(tagsRoot, "Map.Tag.Type.ixx")
    if _WriteIfChanged(outPath, content):
        print(f"  Generated Module:    {outPath}")
    return outPath


def GenerateSystemUmbrella(prefixes: list[str], tagsRoot: str) -> str:
    lines = []
    lines.append(f"// Auto-generated by TagTranspiler (GenerateCatalog.py)")
